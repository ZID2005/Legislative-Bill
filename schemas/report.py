"""
schemas/report.py
=================
Typed data models for the Stakeholder Reporting & Presentation Layer (Task 7.3).

Defines:
1. StakeholderType   — INVESTOR / BUSINESS / PUBLIC enum
2. ReportFormat      — JSON / MARKDOWN / CSV enum
3. StakeholderReport — Full per-(bill × company × stakeholder) report
4. BillLevelReport   — Aggregated bill-level summary across companies
5. CompanyLevelReport — Company → Bills aggregated view
6. ReportValidationReport — Pre-save validation audit
7. Deterministic ID generation helpers

Design Invariants
-----------------
- Reports are read-only views of DecisionSupportRecord outputs.
- No prediction logic, risk formulas, or ML models are present here.
- All probability and score fields are carried through verbatim from
  the upstream DecisionSupportRecord — never recomputed.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Optional


# ---------------------------------------------------------------------------
# Helper: sanitize IDs for filesystem safety
# ---------------------------------------------------------------------------


def _sanitize(identifier: str) -> str:
    """Sanitize identifier string for deterministic OS-safe IDs."""
    if not identifier:
        return ""
    return (
        str(identifier)
        .replace("/", "_")
        .replace("\\", "_")
        .replace(":", "_")
        .replace(" ", "_")
        .replace("[", "")
        .replace("]", "")
        .replace("+", "p")
        .replace(",", "_")
    )


def make_report_id(
    bill_id: str,
    company_isin: str,
    event_window: str,
    stakeholder_type: str,
) -> str:
    """
    Generate a deterministic, unique report ID for a
    (bill, company, event_window, stakeholder_type) tuple.

    Formula: ``rpt_{bill_id}_{company_isin}_{event_window}_{stakeholder_type}``
    (all components sanitized for filesystem safety).
    """
    b = _sanitize(bill_id)
    i = _sanitize(company_isin)
    w = _sanitize(event_window)
    s = _sanitize(stakeholder_type).lower()
    return f"rpt_{b}_{i}_{w}_{s}"


def make_bill_report_id(bill_id: str) -> str:
    """Generate a deterministic ID for a bill-level aggregation report."""
    b = _sanitize(bill_id)
    return f"bill_rpt_{b}"


def make_company_report_id(company_isin: str) -> str:
    """Generate a deterministic ID for a company-level aggregation report."""
    i = _sanitize(company_isin)
    return f"co_rpt_{i}"


def make_validation_report_id(report_id: str) -> str:
    """Generate validation report ID from parent report ID."""
    return f"val_{report_id}"


