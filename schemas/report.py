@dataclass
class StakeholderReport:
    """
    Strongly-typed, structured stakeholder report for a
    (bill × company × event_window × stakeholder_type) observation.

    This is a read-only presentation artefact — it does NOT modify
    predictions, risk scores, or any model outputs from upstream tasks.

    Fields
    ------
    report_id : str
        Deterministic unique identifier. Generated by ``make_report_id()``.
    bill_id : str
    company_isin : str
    event_window : str
    stakeholder_type : str
        One of INVESTOR / BUSINESS / PUBLIC.
    decision_version : str
        Version of the upstream DecisionSupportRecord used to build this report.
        Used for incremental regeneration checks.
    generated_timestamp : str
        ISO-8601 UTC timestamp of report generation.
    report_version : str
        Semantic version of the reporting engine (e.g. "v1.0").
    executive_summary : str
        2–3 sentence high-level summary tailored to the stakeholder type.
    bill_summary : str
        Bill name, type, ministry, house, introduction date.
    company_summary : str
        Company name, ISIN, sector, market cap category.
    impact_summary : str
        Direction probability, market-moving probability, impact score,
        impact category — presented in stakeholder-appropriate language.
    risk_summary : str
        Risk score, risk category, pricing-in risk — in audience language.
    anticipation_summary : str
        Anticipation classification and score interpretation.
    confidence_summary : str
        Model confidence tier and scalar score.
    key_factors : list[str]
        Top model factors (SHAP features where available) or narrative factors.
    methodology_note : str
        Fixed academic methodology statement.
    disclaimer : str
        Required legal/academic disclaimer text.
    """

    report_id: str
    bill_id: str
    company_isin: str
    event_window: str
    stakeholder_type: str
    decision_version: str
    generated_timestamp: str
    report_version: str
    executive_summary: str
    bill_summary: str
    company_summary: str
    impact_summary: str
    risk_summary: str
    anticipation_summary: str
    confidence_summary: str
    key_factors: list[str] = field(default_factory=list)
    methodology_note: str = ""
    disclaimer: str = ""

    def __post_init__(self) -> None:
        if not self.report_id:
            self.report_id = make_report_id(
                self.bill_id,
                self.company_isin,
                self.event_window,
                self.stakeholder_type,
            )
        if not self.generated_timestamp:
            self.generated_timestamp = (
                datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
            )

    def to_dict(self) -> dict[str, Any]:
        """Serialise to a JSON-safe dictionary."""
        return {
            "report_id": self.report_id,
            "bill_id": self.bill_id,
            "company_isin": self.company_isin,
            "event_window": self.event_window,
            "stakeholder_type": self.stakeholder_type,
            "decision_version": self.decision_version,
            "generated_timestamp": self.generated_timestamp,
            "report_version": self.report_version,
            "executive_summary": self.executive_summary,
            "bill_summary": self.bill_summary,
            "company_summary": self.company_summary,
            "impact_summary": self.impact_summary,
            "risk_summary": self.risk_summary,
            "anticipation_summary": self.anticipation_summary,
            "confidence_summary": self.confidence_summary,
            "key_factors": list(self.key_factors),
            "methodology_note": self.methodology_note,
            "disclaimer": self.disclaimer,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "StakeholderReport":
        """Deserialise from a dictionary."""
        return cls(
            report_id=str(data.get("report_id", "")),
            bill_id=str(data.get("bill_id", "")),
            company_isin=str(data.get("company_isin", "")),
            event_window=str(data.get("event_window", "")),
            stakeholder_type=str(data.get("stakeholder_type", "")),
            decision_version=str(data.get("decision_version", "v1.0")),
            generated_timestamp=str(data.get("generated_timestamp", "")),
            report_version=str(data.get("report_version", "v1.0")),
            executive_summary=str(data.get("executive_summary", "")),
            bill_summary=str(data.get("bill_summary", "")),
            company_summary=str(data.get("company_summary", "")),
            impact_summary=str(data.get("impact_summary", "")),
            risk_summary=str(data.get("risk_summary", "")),
            anticipation_summary=str(data.get("anticipation_summary", "")),
            confidence_summary=str(data.get("confidence_summary", "")),
            key_factors=list(data.get("key_factors", [])),
            methodology_note=str(data.get("methodology_note", "")),
            disclaimer=str(data.get("disclaimer", "")),
        )


