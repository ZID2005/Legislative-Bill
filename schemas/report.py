@dataclass
class BillLevelReport:
    """
    Bill-level aggregation report across all companies affected by a single bill.

    Aggregation Formulas (documented)
    ----------------------------------
    - total_companies    : count of unique company ISINs in the input records
    - positive_count     : count where predicted_direction == "POSITIVE"
    - negative_count     : count where predicted_direction == "NEGATIVE"
    - neutral_count      : count where predicted_direction == "NEUTRAL"
    - market_moving_count: count where market_moving_probability >= 0.50
    - high_impact_count  : count where impact_category in {"HIGH", "VERY_HIGH"}
    - avg_impact_score   : arithmetic mean of impact_score values (NOT probabilities)
    - avg_risk_score     : arithmetic mean of risk_score values (NOT probabilities)
    - anticipation_distribution: frequency count of anticipation_class values
    - sectors_affected   : sorted unique list of sector values
    - risk_distribution  : frequency count of risk_category values
    """

    report_id: str
    bill_id: str
    bill_title: str
    bill_ministry: str
    bill_year: Optional[int]
    event_window: str
    generated_timestamp: str
    report_version: str
    total_companies: int
    positive_count: int
    negative_count: int
    neutral_count: int
    market_moving_count: int
    high_impact_count: int
    avg_impact_score: float
    avg_risk_score: float
    anticipation_distribution: dict[str, int]
    risk_distribution: dict[str, int]
    sectors_affected: list[str]
    company_summaries: list[dict[str, Any]] = field(default_factory=list)
    methodology_note: str = ""
    disclaimer: str = ""

    def __post_init__(self) -> None:
        if not self.report_id:
            self.report_id = make_bill_report_id(self.bill_id)
        if not self.generated_timestamp:
            self.generated_timestamp = (
                datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
            )

    def to_dict(self) -> dict[str, Any]:
        """Serialise to a JSON-safe dictionary."""
        return {
            "report_id": self.report_id,
            "bill_id": self.bill_id,
            "bill_title": self.bill_title,
            "bill_ministry": self.bill_ministry,
            "bill_year": self.bill_year,
            "event_window": self.event_window,
            "generated_timestamp": self.generated_timestamp,
            "report_version": self.report_version,
            "total_companies": self.total_companies,
            "positive_count": self.positive_count,
            "negative_count": self.negative_count,
            "neutral_count": self.neutral_count,
            "market_moving_count": self.market_moving_count,
            "high_impact_count": self.high_impact_count,
            "avg_impact_score": round(float(self.avg_impact_score), 4),
            "avg_risk_score": round(float(self.avg_risk_score), 4),
            "anticipation_distribution": dict(self.anticipation_distribution),
            "risk_distribution": dict(self.risk_distribution),
            "sectors_affected": list(self.sectors_affected),
            "company_summaries": list(self.company_summaries),
            "methodology_note": self.methodology_note,
            "disclaimer": self.disclaimer,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "BillLevelReport":
        """Deserialise from a dictionary."""
        return cls(
            report_id=str(data.get("report_id", "")),
            bill_id=str(data.get("bill_id", "")),
            bill_title=str(data.get("bill_title", "")),
            bill_ministry=str(data.get("bill_ministry", "")),
            bill_year=data.get("bill_year"),
            event_window=str(data.get("event_window", "")),
            generated_timestamp=str(data.get("generated_timestamp", "")),
            report_version=str(data.get("report_version", "v1.0")),
            total_companies=int(data.get("total_companies", 0)),
            positive_count=int(data.get("positive_count", 0)),
            negative_count=int(data.get("negative_count", 0)),
            neutral_count=int(data.get("neutral_count", 0)),
            market_moving_count=int(data.get("market_moving_count", 0)),
            high_impact_count=int(data.get("high_impact_count", 0)),
            avg_impact_score=float(data.get("avg_impact_score", 0.0)),
            avg_risk_score=float(data.get("avg_risk_score", 0.0)),
            anticipation_distribution=dict(
                data.get("anticipation_distribution", {})
            ),
            risk_distribution=dict(data.get("risk_distribution", {})),
            sectors_affected=list(data.get("sectors_affected", [])),
            company_summaries=list(data.get("company_summaries", [])),
            methodology_note=str(data.get("methodology_note", "")),
            disclaimer=str(data.get("disclaimer", "")),
        )


