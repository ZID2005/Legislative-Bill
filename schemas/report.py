@dataclass
class ReportValidationReport:
    """
    Validation audit report generated during report pre-save checks.
    """

    validation_id: str
    report_id: str
    bill_id: str
    company_isin: str
    stakeholder_type: str
    is_valid: bool = True
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    checks_performed: dict[str, bool] = field(default_factory=dict)
    timestamp: str = field(
        default_factory=lambda: datetime.now(timezone.utc)
        .isoformat()
        .replace("+00:00", "Z")
    )

    def __post_init__(self) -> None:
        if self.errors:
            self.is_valid = False
        if not self.validation_id:
            self.validation_id = make_validation_report_id(self.report_id)

    def to_dict(self) -> dict[str, Any]:
        """Serialise to a JSON-safe dictionary."""
        return {
            "validation_id": self.validation_id,
            "report_id": self.report_id,
            "bill_id": self.bill_id,
            "company_isin": self.company_isin,
            "stakeholder_type": self.stakeholder_type,
            "is_valid": bool(self.is_valid),
            "errors": list(self.errors),
            "warnings": list(self.warnings),
            "checks_performed": dict(self.checks_performed),
            "timestamp": self.timestamp,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "ReportValidationReport":
        """Deserialise from a dictionary."""
        return cls(
            validation_id=str(data.get("validation_id", "")),
            report_id=str(data.get("report_id", "")),
            bill_id=str(data.get("bill_id", "")),
            company_isin=str(data.get("company_isin", "")),
            stakeholder_type=str(data.get("stakeholder_type", "")),
            is_valid=bool(data.get("is_valid", True)),
            errors=list(data.get("errors", [])),
            warnings=list(data.get("warnings", [])),
            checks_performed=dict(data.get("checks_performed", {})),
            timestamp=str(data.get("timestamp", "")),
        )
